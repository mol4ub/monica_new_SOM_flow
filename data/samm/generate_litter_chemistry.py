"""Generate src/core/samm-litter-chemistry.cpp from data/samm/litter-chemistry.csv.

usage (from the repository root): python3 data/samm/generate_litter_chemistry.py

CSV columns (lignin and polyphenol contents in kg per kg dry matter, i.e. g/kg / 1000):
  kind              residue | fertiliser | default_residue | default_fertiliser
  key               crop residue species or organic fertiliser id as in the monica-parameters files
  lignin, polyphenols, root_lignin, root_polyphenols
  (any further columns, e.g. name, group, sources, notes, are documentation only)
"""
import csv
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CSV = os.path.join(HERE, "litter-chemistry.csv")
OUT = os.path.join(ROOT, "src", "core", "samm-litter-chemistry.cpp")


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def num(v, field, key):
    try:
        x = float(v)
    except ValueError:
        raise SystemExit(f"{key}: {field} '{v}' is not a number")
    if not 0 <= x < 1:
        raise SystemExit(f"{key}: {field} {x} must be a fraction of dry matter (0..1)")
    return x


def main():
    rows = {"residue": [], "fertiliser": []}
    defaults = {}
    seen = set()
    with open(CSV, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if not r["kind"] or r["kind"].startswith("#"):
                continue
            vals = [num(r[c], c, r["key"]) for c in ("lignin", "polyphenols", "root_lignin", "root_polyphenols")]
            if r["kind"] in ("default_residue", "default_fertiliser"):
                defaults[r["kind"]] = vals
                continue
            k = (r["kind"], norm(r["key"]))
            if k in seen:
                raise SystemExit(f"duplicate {k}")
            seen.add(k)
            rows[r["kind"]].append((norm(r["key"]), vals))
    for d in ("default_residue", "default_fertiliser"):
        if d not in defaults:
            raise SystemExit(f"missing row of kind {d}")

    def entries(lst):
        return "\n".join(f'  {{"{k}", {v[0]!r}, {v[1]!r}, {v[2]!r}, {v[3]!r}}},' for k, v in sorted(lst))

    def entry(name, v):
        return f'  static const LitterChemistry c{{"{name}", {v[0]!r}, {v[1]!r}, {v[2]!r}, {v[3]!r}}};\n  return c;'

    src = f'''/* This Source Code Form is subject to the terms of the Mozilla Public
* License, v. 2.0. If a copy of the MPL was not distributed with this
* file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// GENERATED by data/samm/generate_litter_chemistry.py from data/samm/litter-chemistry.csv - do not edit.

#include "samm-litter-chemistry.h"

#include <cctype>
#include <vector>

namespace samm {{

namespace {{
const std::vector<LitterChemistry> RESIDUES = {{
{entries(rows["residue"])}
}};

const std::vector<LitterChemistry> FERTILISERS = {{
{entries(rows["fertiliser"])}
}};

const LitterChemistry* find(const std::vector<LitterChemistry>& table, const std::string& key) {{
  auto k = normaliseChemistryKey(key);
  for (const auto& e : table) if (k == e.key) return &e;
  return nullptr;
}}
}} // namespace

std::string normaliseChemistryKey(const std::string& s) {{
  std::string r;
  for (unsigned char c : s) if (std::isalnum(c)) r += char(std::tolower(c));
  return r;
}}

const LitterChemistry* residueChemistry(const std::string& species) {{ return find(RESIDUES, species); }}

const LitterChemistry* fertiliserChemistry(const std::string& id) {{ return find(FERTILISERS, id); }}

const LitterChemistry& defaultResidueChemistry() {{
{entry("default_residue", defaults["default_residue"])}
}}

const LitterChemistry& defaultFertiliserChemistry() {{
{entry("default_fertiliser", defaults["default_fertiliser"])}
}}

}} // namespace samm
'''
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"wrote {OUT}: {len(rows['residue'])} residues, {len(rows['fertiliser'])} fertilisers")


if __name__ == "__main__":
    main()
